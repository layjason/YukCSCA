export type RouteId = (typeof routeManifest)[number]['id'];

export const primaryNavRoutes = routeManifest.filter(
  (route) => route.navigation === 'primary' && route.audience === 'student',
);
export const mobilePrimaryNavRoutes = routeManifest.filter(
  (route) => route.mobileNavigation === 'primary' && route.audience === 'student',
);
export const mobileMoreRoutes = routeManifest.filter(
  (route) => route.mobileNavigation === 'more' && route.audience === 'student',
);
export const parentNavRoutes = routeManifest.filter(
  (route) => route.navigation === 'primary' && route.audience === 'parent-preview',
);
export const parentMobileNavRoutes = routeManifest.filter(
  (route) => route.mobileNavigation === 'primary' && route.audience === 'parent-preview',
);
export const publicNavRoutes = routeManifest.filter(
  (route) => route.navigation === 'primary' && route.audience === 'public',
);

export function routesForAccess(access: RouteAccess) {
  return routeManifest.filter((route) => route.access === access);
}

export function getRouteById(id: RouteId): AppRouteDefinition {
  const found = routeManifest.find((route) => route.id === id);
  if (!found) {
    throw new Error(`Unknown route id: ${id}`);
  }
  return found;
}

export function isRouteActive(route: AppRouteDefinition, pathname: string): boolean {
  const activePaths = route.activePaths ?? [{ path: route.path }];
  return activePaths.some((activePath) =>
    activePath.exact ? pathname === activePath.path : pathname.startsWith(activePath.path),
  );
}

function route<const I extends string, const A extends RouteAccess>(
  id: I,
  path: string,
  labelKey: string,
  availability: RouteAvailability,
  access: A,
  audience: RouteAudience,
  navigation: NavigationPlacement,
  requirementAreas: string[],
  prototypeOnly = false,
  mobileNavigation?: MobileNavigationPlacement,
  activePaths?: readonly RouteActivePath[],
): AppRouteDefinition & { readonly id: I; readonly access: A } {
  return {
    id,
    path,
    labelKey,
    availability,
    access,
    audience,
    navigation,
    ...(mobileNavigation ? { mobileNavigation } : {}),
    requirementAreas,
    ...(activePaths ? { activePaths } : {}),
    ...(prototypeOnly ? { prototypeOnly: true } : {}),
  };
}
