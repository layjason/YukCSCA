export type RouteAvailability = 'implemented' | 'prototype' | 'unavailable';
export type RouteAudience = 'public' | 'student' | 'parent-preview' | 'account';
export type RouteAccess =
  | 'public'
  | 'unsupported'
  | 'role-selection'
  | 'parent-onboarding'
  | 'parent-preview'
  | 'commerce-preview'
  | 'preview-context'
  | 'production-auth'
  | 'student-onboarding-preview'
  | 'student-workspace-preview';

export type NavigationPlacement = 'primary' | 'secondary' | 'hidden';
export type MobileNavigationPlacement = 'primary' | 'more' | 'hidden';

export interface AppRouteDefinition {
  id: string;
  path: string;
  labelKey: string;
  availability: RouteAvailability;
  access: RouteAccess;
  audience: RouteAudience;
  navigation: NavigationPlacement;
  mobileNavigation?: MobileNavigationPlacement;
  requirementAreas: string[];
  activePaths?: readonly RouteActivePath[];
  prototypeOnly?: boolean;
}

export interface RouteActivePath {
  path: string;
  exact?: boolean;
}

function defineRoutes<const T extends readonly AppRouteDefinition[]>(routes: T): T {
  return routes;
}

